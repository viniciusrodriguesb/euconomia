import AxeBuilder from '@axe-core/playwright';
import { expect, test } from '@playwright/test';

test('cadastro confirmado e recuperação de senha sem envio de e-mail', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/criar-conta');
  const email = `recuperacao-${Date.now()}@example.com`;
  const senha = 'Inicial!01234569';
  const novaSenha = 'Renovada!01234569';
  await page.getByLabel('E-mail', { exact: true }).fill(email);
  await page.getByLabel('Confirme o e-mail', { exact: true }).fill('diferente@example.com');
  await page.getByLabel('Senha', { exact: true }).fill(senha);
  await page.getByLabel('Confirme a senha', { exact: true }).fill('Diferente!01234569');
  await expect(page.getByText('Os e-mails devem ser iguais.')).toBeVisible();
  await expect(page.getByText('As senhas devem ser iguais.')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Cadastrar e entrar' })).toBeDisabled();
  await page.getByLabel('Confirme o e-mail', { exact: true }).fill(email);
  await page.getByLabel('Confirme a senha', { exact: true }).fill(senha);
  await page.getByRole('button', { name: 'Cadastrar e entrar' }).click();
  const codigo = await page.getByLabel('Código de recuperação', { exact: true }).inputValue();
  expect(codigo).toMatch(/^[A-F0-9]{64}$/);
  await expect(page.getByRole('button', { name: 'Continuar', exact: true })).toBeDisabled();
  await page.screenshot({ path: testInfo.outputPath('codigo-recuperacao-mobile.png') });
  const acessibilidadeCodigo = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze();
  expect(acessibilidadeCodigo.violations.map(x => x.id)).toEqual([]);
  await page.getByLabel('Guardei meu código em um local seguro').check();
  await page.getByRole('button', { name: 'Continuar', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Visão geral', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Sair', exact: true }).click();
  await page.getByRole('link', { name: 'Esqueci minha senha' }).click();
  await expect(page.getByRole('heading', { name: 'Redefinir senha', exact: true })).toBeVisible();
  await page.getByLabel('E-mail', { exact: true }).fill(email);
  await page.getByLabel('Código de recuperação', { exact: true }).fill(codigo);
  await page.getByLabel('Nova senha', { exact: true }).fill(novaSenha);
  await page.getByLabel('Confirme a nova senha', { exact: true }).fill(novaSenha);
  const acessibilidadeRedefinicao = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze();
  expect(acessibilidadeRedefinicao.violations.map(x => x.id)).toEqual([]);
  await page.getByRole('button', { name: 'Redefinir senha', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Senha redefinida.' })).toBeVisible();
  await page.getByRole('link', { name: 'Voltar para entrar' }).click();
  await expect(page.getByRole('heading', { name: 'Entre na sua conta', exact: true })).toBeVisible();
  await page.getByLabel('E-mail', { exact: true }).fill(email);
  await page.getByLabel('Senha', { exact: true }).fill(novaSenha);
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Visão geral', exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Segurança', exact: true }).click();
  await page.getByLabel('Senha atual').fill(novaSenha);
  await page.getByRole('button', { name: 'Gerar código de recuperação' }).click();
  await expect(page.getByLabel('Código de recuperação', { exact: true })).not.toHaveValue(codigo);
  await page.getByLabel('Guardei meu código em um local seguro').check();
  await page.getByRole('button', { name: 'Continuar', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Segurança da conta' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
});

test('cadastro, compra parcelada, ajuste mensal e conferência', async ({ page }, testInfo) => {
  const agora = new Date();
  const atual = `${agora.getFullYear()}-${String(agora.getMonth() + 1).padStart(2, '0')}`;
  const dataAnterior = new Date(agora.getFullYear(), agora.getMonth() - 1, 1);
  const anterior = `${dataAnterior.getFullYear()}-${String(dataAnterior.getMonth() + 1).padStart(2, '0')}`;
  const falhas: string[] = [];
  page.on('pageerror', erro => falhas.push(erro.message));
  await page.goto('/');
  await expect(page).toHaveTitle('Entrar · Euconomia');
  await expect(page.getByRole('heading', { name: 'Euconomia' })).toBeVisible();
  const favicon = await page.request.get('/imagens/euconomia-icone.png');
  expect(favicon.headers()['content-type']).toContain('image/png');
  await page.getByRole('link', { name: 'Criar conta', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Crie sua conta', exact: true })).toBeVisible();
  const email = `navegador-${Date.now()}@example.com`;
  await page.getByLabel('E-mail', { exact: true }).fill(email);
  await page.getByLabel('Confirme o e-mail', { exact: true }).fill(email);
  await page.getByLabel('Senha', { exact: true }).fill('Teste!01234569');
  await page.getByLabel('Confirme a senha', { exact: true }).fill('Teste!01234569');
  await page.getByRole('button', { name: 'Cadastrar e entrar' }).click();
  await expect(page.getByRole('heading', { name: 'Guarde seu código de recuperação' })).toBeVisible();
  await page.getByLabel('Guardei meu código em um local seguro').check();
  await page.getByRole('button', { name: 'Continuar', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Visão geral' })).toBeVisible();
  await expect(page.getByText('Saldo atual em caixa')).toBeVisible();
  await page.getByRole('link', { name: 'Cadastros', exact: true }).click();
  await page.getByLabel('Nome da conta', { exact: true }).fill('Conta da casa');
  await page.getByLabel('Saldo inicial (R$)', { exact: true }).fill('2000,00');
  await page.getByLabel('Data do saldo inicial', { exact: true }).fill(`${anterior}-01`);
  await page.getByRole('button', { name: 'Adicionar conta' }).click();
  await expect(page.getByText('Conta adicionada.')).toBeVisible();
  await page.getByLabel('Nome do cartão').fill('Cartão azul');
  await page.getByLabel('Bandeira').fill('Visa');
  await page.getByLabel('Conta de pagamento').selectOption({ label: 'Conta da casa' });
  await page.getByLabel('Limite (R$)', { exact: true }).fill('4000,00');
  await page.getByRole('button', { name: 'Adicionar cartão' }).click();
  await expect(page.getByText('Cartão salvo.')).toBeVisible();
  await page.getByRole('link', { name: 'Lançamentos', exact: true }).click();
  await page.getByLabel('Forma de pagamento').selectOption('CartaoCredito');
  await page.getByRole('combobox', { name: 'Cartão', exact: true }).selectOption({ label: 'Cartão azul' });
  await page.getByRole('combobox', { name: 'Categoria', exact: true }).selectOption({ label: 'Moradia' });
  await page.getByLabel('Valor (R$)', { exact: true }).fill('1000,00');
  await page.getByLabel('Descrição', { exact: true }).fill('Compra teste');
  await page.getByLabel('Data da compra').fill(`${anterior}-05`);
  await page.getByLabel('Quantidade de parcelas').fill('3');
  await page.getByRole('button', { name: 'Conferir efeito' }).click();
  const efeito = page.getByRole('region', { name: 'Resumo de efeito' });
  await expect(efeito).toContainText(/R\$\s0,00/);
  await expect(efeito).toContainText(/3\/3 . R\$\s333,34/);
  await efeito.getByRole('button', { name: 'Confirmar lançamento' }).click();
  await expect(page.getByText('Lançamento registrado.')).toBeVisible();
  await expect(page.getByRole('table').getByText('Compra teste', { exact: true })).toHaveCount(3);
  const tamanhoExtrato = page.getByLabel('Itens por página');
  await expect(tamanhoExtrato).toHaveValue('20');
  const extratoPaginado = page.waitForResponse(resposta =>
    new URL(resposta.url()).pathname === '/api/lancamentos' && new URL(resposta.url()).searchParams.get('tamanho') === '10');
  await tamanhoExtrato.selectOption('10');
  expect((await extratoPaginado).ok()).toBe(true);
  await expect(tamanhoExtrato).toHaveValue('10');

  await page.getByRole('link', { name: 'Recorrências', exact: true }).click();
  await page.getByRole('button', { name: 'Nova regra', exact: true }).click();
  await page.getByLabel('Descrição', { exact: true }).fill('Reserva mensal');
  await page.getByRole('combobox', { name: 'Tipo', exact: true }).selectOption('AporteFixo');
  await page.getByLabel('Valor padrão (R$)').fill('1000');
  await page.getByRole('combobox', { name: 'Conta', exact: true }).selectOption({ label: 'Conta da casa' });
  await page.getByRole('combobox', { name: 'Categoria', exact: true }).selectOption({ label: 'Investimentos' });
  await page.getByRole('button', { name: 'Salvar regra' }).click();
  await expect(page.getByText('Regra criada.')).toBeVisible();
  const linhas = page.getByRole('row').filter({ hasText: 'Reserva mensal' });
  await expect(linhas).toHaveCount(6);
  await linhas.first().getByRole('button', { name: 'Ajustar', exact: true }).click();
  await page.getByLabel('Novo valor (R$)').fill('2000');
  await page.getByRole('button', { name: 'Aplicar ajuste' }).click();
  await expect(linhas.first()).toContainText('Ajustado');
  await expect(linhas.first()).toContainText(/R\$\s2\.000,00/);
  await expect(linhas.nth(1)).toContainText(/R\$\s1\.000,00/);

  await page.getByRole('combobox', { name: 'Horizonte' }).selectOption({ label: '12 meses' });
  await page.getByRole('button', { name: 'Aplicar filtros' }).click();
  await expect(linhas).toHaveCount(10);
  await page.getByRole('button', { name: 'Próxima' }).click();
  await expect(linhas).toHaveCount(2);
  await page.getByLabel('Itens por página').selectOption('20');
  await expect(linhas).toHaveCount(12);
  await expect(page.getByLabel('Itens por página')).toHaveValue('20');

  let liberarFaturas!: () => void;
  let liberarParcelas!: () => void;
  const aguardarFaturas = new Promise<void>(resolve => { liberarFaturas = resolve; });
  const aguardarParcelas = new Promise<void>(resolve => { liberarParcelas = resolve; });
  const rotaFaturas = /\/api\/faturas\?/;
  const rotaParcelas = /\/api\/parcelas\?/;
  await page.route(rotaFaturas, async rota => { await aguardarFaturas; await rota.continue(); });
  await page.route(rotaParcelas, async rota => { await aguardarParcelas; await rota.continue(); });
  await page.getByRole('link', { name: 'Cartões e parcelas', exact: true }).click();
  const carregamento = page.getByText('Carregando dados…', { exact: true });
  try {
    await expect(carregamento).toBeVisible();
    const imagem = page.locator('app-carregamento-api img');
    await expect(imagem).toHaveJSProperty('complete', true);
    await expect(imagem).toHaveJSProperty('naturalWidth', 88);
    expect(await imagem.evaluate((img: HTMLImageElement) => img.currentSrc)).toMatch(/\/growth-88\.webp$/);

    const faturasRespondidas = page.waitForResponse(rotaFaturas);
    liberarFaturas();
    await faturasRespondidas;
    await expect(carregamento).toBeVisible();
  } finally {
    liberarFaturas();
    liberarParcelas();
  }
  await expect(carregamento).toBeHidden();
  await page.unroute(rotaFaturas);
  await page.unroute(rotaParcelas);
  await page.getByLabel('A partir de', { exact: true }).fill(anterior);
  await page.getByRole('button', { name: 'Aplicar filtros' }).click();
  await page.getByRole('button', { name: 'Pagar fatura', exact: true }).first().click();
  await page.getByRole('button', { name: 'Confirmar pagamento' }).click();
  await expect(page.getByText('Fatura paga.')).toBeVisible();
  await page.getByRole('link', { name: 'Visão geral', exact: true }).click();
  await expect(page.getByLabel('Mês inicial')).toHaveValue(atual);
  await expect(page.getByText('Saldo atual em caixa').locator('..')).toContainText(/R\$\s1\.666,67/);
  const fluxo = page.getByRole('heading', { name: 'Fluxo de caixa projetado' }).locator('xpath=ancestor::section[1]');
  await expect(fluxo.locator('tbody tr')).toHaveCount(3);
  await fluxo.getByRole('button', { name: /Ver mais/ }).click();
  await expect(fluxo.locator('tbody tr')).toHaveCount(12);
  await fluxo.getByRole('button', { name: /Ver menos/ }).click();
  await expect(fluxo.locator('tbody tr')).toHaveCount(3);
  await page.getByRole('button', { name: 'Conferir registros' }).click();
  await expect(page.getByRole('status').filter({ hasText: '0 divergências' })).toBeVisible();
  const menu = page.getByRole('navigation', { name: 'Menu principal' });
  for (const width of [1440, 960, 768, 320, 390]) {
    await page.setViewportSize({ width, height: 844 });
    await expect(menu.getByRole('link')).toHaveCount(5);
    await expect(menu.getByRole('link', { name: 'Visão geral', exact: true })).toHaveAttribute('aria-current', 'page');
    await expect(menu).toHaveCSS('position', width < 960 ? 'fixed' : 'static');
    if (width < 960) {
      const limites = (await menu.boundingBox())!;
      expect(limites.x).toBeGreaterThan(0);
      expect(limites.x + limites.width).toBeLessThan(width);
      expect(limites.y + limites.height).toBeLessThan(844);
      await expect(menu).toHaveCSS('border-radius', '32px');
    }
    await expect(page.getByRole('heading', { name: 'Evolução mensal' })).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  }
  await menu.getByRole('link', { name: 'Cartões e parcelas', exact: true }).click();
  await expect(page).toHaveURL(/\/cartoes$/);
  await expect(menu.getByRole('link', { name: 'Cartões e parcelas', exact: true })).toHaveAttribute('aria-current', 'page');
  await menu.getByRole('link', { name: 'Visão geral', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Evolução mensal' })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('menu-mobile-flutuante.png') });
  const acessibilidade = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze();
  expect(acessibilidade.violations.map(x => ({ id: x.id, elementos: x.nodes.map(n => n.target) }))).toEqual([]);
  expect(falhas).toEqual([]);
});
